<?php

session_start();

require_once "../config/database.php";


/*
|--------------------------------------------------------------------------
| CEK LOGIN
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION['admin_id'])) {

    header("Location: ../auth/login.php");
    exit;

}


/*
|--------------------------------------------------------------------------
| DATA ADMIN YANG SEDANG LOGIN
|--------------------------------------------------------------------------
*/

$currentAdminId = (int) $_SESSION['admin_id'];


/*
|--------------------------------------------------------------------------
| AMBIL ID ADMIN YANG AKAN DIHAPUS
|--------------------------------------------------------------------------
*/

$id = isset($_GET['id'])
    ? (int) $_GET['id']
    : 0;


/*
|--------------------------------------------------------------------------
| VALIDASI ID
|--------------------------------------------------------------------------
*/

if ($id <= 0) {

    header("Location: admin.php");
    exit;

}


/*
|--------------------------------------------------------------------------
| CEGAH HAPUS AKUN SENDIRI
|--------------------------------------------------------------------------
*/

if ($id === $currentAdminId) {

    header("Location: admin.php?error=cannot_delete_self");
    exit;

}


/*
|--------------------------------------------------------------------------
| CEK DATA ADMIN
|--------------------------------------------------------------------------
*/

$stmtCheck = $pdo->prepare("
    SELECT
        id,
        nama_lengkap,
        username
    FROM admin
    WHERE id = ?
    LIMIT 1
");

$stmtCheck->execute([$id]);

$admin = $stmtCheck->fetch();


/*
|--------------------------------------------------------------------------
| JIKA ADMIN TIDAK DITEMUKAN
|--------------------------------------------------------------------------
*/

if (!$admin) {

    header("Location: admin.php?error=admin_not_found");
    exit;

}


/*
|--------------------------------------------------------------------------
| HAPUS ADMIN
|--------------------------------------------------------------------------
*/

$stmtDelete = $pdo->prepare("
    DELETE FROM admin
    WHERE id = ?
    LIMIT 1
");

$stmtDelete->execute([$id]);


/*
|--------------------------------------------------------------------------
| CEK HASIL HAPUS
|--------------------------------------------------------------------------
*/

if ($stmtDelete->rowCount() > 0) {

    header("Location: admin.php?success=admin_deleted");
    exit;

}


/*
|--------------------------------------------------------------------------
| JIKA GAGAL
|--------------------------------------------------------------------------
*/

header("Location: admin.php?error=delete_failed");
exit;

?>